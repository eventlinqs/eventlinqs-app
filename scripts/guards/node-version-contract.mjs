/**
 * BUILD-FAILING GUARD: no build script may use a Node API newer than CI runs.
 *
 * THE DEFECT THIS EXISTS TO STOP. On 2026-08-05 three guards imported
 * `globSync` from `node:fs`. That export landed in Node 22; CI pins Node 20;
 * the author's machine runs Node 24. All three crashed at IMPORT time in CI with
 *
 *   SyntaxError: The requested module 'node:fs' does not provide an export
 *   named 'globSync'
 *
 * while passing perfectly on the author's machine. Every local gate was green.
 * The gate was measured on the wrong runtime, so the green meant nothing.
 *
 * THE CONTRACT. `.nvmrc` at the repository root is the single definition of the
 * Node major the platform is tested on. CI reads it through
 * `actions/setup-node`'s `node-version-file`, so the contract and the runtime
 * CI installs cannot drift apart by hand-editing one of them.
 *
 * HOW IT CHECKS: an ALLOWLIST, not a denylist. `lib/node-surface.json` records
 * what Node 20 ACTUALLY HAS, enumerated by Node 20 itself. Anything a script
 * imports or reaches for that is absent from that record is a violation. This
 * matters: a denylist only knows the APIs somebody remembered to add, so it
 * would have caught `globSync` and missed the next one. An allowlist catches an
 * API added in Node 25 on the day it is used, with no list to maintain.
 *
 * WHAT IT STILL CANNOT DO. Read this before trusting it.
 *
 *   COMPLETE for named imports of built-in modules, for built-in module names,
 *   and for static members of the well-known globals. That covers the 2026-08-05
 *   failure and every failure shaped like it, including the import-time
 *   SyntaxError class, which is the dangerous one: the script dies before line
 *   one, so no amount of runtime testing on a newer Node reveals it.
 *
 *   NOT COMPLETE for prototype methods such as `.symmetricDifference(`, because
 *   the receiver's type is not knowable without type inference, so those keep a
 *   small hand-maintained list below. Dynamic access such as
 *   fs['glob' + 'Sync'] defeats any static check whatsoever.
 *
 * Because it is not total, it is the first of three layers, not the only one:
 *
 *   `npm run guards:contract-node` executes the whole guard suite under the
 *   contract Node itself. That is the complete check, because it is not a check
 *   at all: it is the real runtime.
 *
 *   `run-guards.mjs` prints a NOT CI-EQUIVALENT banner whenever the Node it runs
 *   on is not the contract major, so a green local run can never again be
 *   silently mistaken for a green CI run.
 *
 * Run by `npm run guards`, which `prebuild` invokes, so `npm run build` fails.
 */
import { readFileSync, readdirSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, relative } from 'node:path'
import { readSource, lineAt } from './lib/source.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = process.cwd()
const failures = []

const die = (message) => {
  console.error('\n[node-version-contract] FAILED\n')
  console.error(`${message}\n`)
  process.exit(1)
}

// ---------------------------------------------------------------------------
// The contract, and the surface record that must match it.
// ---------------------------------------------------------------------------

const NVMRC = join(ROOT, '.nvmrc')
if (!existsSync(NVMRC)) {
  die(
    '  .nvmrc is missing. It is the single definition of the Node major this\n' +
      '  platform is tested on, and CI reads it via node-version-file. Without it\n' +
      '  there is no contract to check against.',
  )
}

const CONTRACT_MAJOR = Number.parseInt(readFileSync(NVMRC, 'utf8').trim().replace(/^v/, ''), 10)
if (!Number.isInteger(CONTRACT_MAJOR)) die('  .nvmrc does not contain a Node major version.')

const SURFACE_PATH = join(HERE, 'lib', 'node-surface.json')
if (!existsSync(SURFACE_PATH)) {
  die(
    `  scripts/guards/lib/node-surface.json is missing. It records what Node\n` +
      `  ${CONTRACT_MAJOR} actually provides. Regenerate it under the contract version:\n` +
      `      npm run guards:surface`,
  )
}

const SURFACE = JSON.parse(readFileSync(SURFACE_PATH, 'utf8'))

if (SURFACE.contractMajor !== CONTRACT_MAJOR) {
  die(
    `  node-surface.json describes Node ${SURFACE.contractMajor} (generated by\n` +
      `  ${SURFACE.generatedBy}) but .nvmrc now pins Node ${CONTRACT_MAJOR}. The record is\n` +
      `  stale, so every verdict below would be about the wrong platform.\n` +
      `  Regenerate it under the new contract version:  npm run guards:surface`,
  )
}

const MODULES = new Set(SURFACE.modules)

/**
 * Prototype methods added after the contract version. These need a hand list
 * because the receiver's type cannot be resolved statically: `a.union(b)` is
 * only a Set method if `a` is a Set, and nothing here knows that. Kept
 * deliberately to names that are unambiguous in practice, because a guard that
 * cries wolf gets switched off, and a switched-off guard is worse than none.
 *
 * Stored as STRINGS and compiled with `new RegExp`, never as regex literals, so
 * that scanning the `code` view (string contents blanked) cannot self-match.
 */
const POST_CONTRACT_PROTOTYPE_METHODS = [
  { token: '.symmetricDifference(', since: 22, instead: 'a manual Set walk' },
  { token: '.isSubsetOf(', since: 22, instead: 'a manual Set walk' },
  { token: '.isSupersetOf(', since: 22, instead: 'a manual Set walk' },
  { token: '.isDisjointFrom(', since: 22, instead: 'a manual Set walk' },
  { token: '.globSync(', since: 22, instead: 'sourceFiles() from ./lib/source.mjs' },
]

// ---------------------------------------------------------------------------
// The scan set: every Node script the repository runs outside the bundler.
// ---------------------------------------------------------------------------

const SCRIPT_EXTENSIONS = ['.mjs', '.js', '.cjs']

function scriptFiles() {
  const out = []

  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue
      const full = join(dir, entry.name)
      if (entry.isDirectory()) walk(full)
      else if (SCRIPT_EXTENSIONS.some((ext) => entry.name.endsWith(ext))) out.push(full)
    }
  }

  walk(join(ROOT, 'scripts'))

  // Root-level config files run under plain Node during lint and build too.
  for (const entry of readdirSync(ROOT, { withFileTypes: true })) {
    if (entry.isFile() && SCRIPT_EXTENSIONS.some((ext) => entry.name.endsWith(ext))) {
      out.push(join(ROOT, entry.name))
    }
  }

  return out.map((f) => relative(ROOT, f).replace(/\\/g, '/')).sort()
}

const FILES = scriptFiles()

/**
 * Is the match at `index` real code, or is it text quoted inside a string?
 *
 * The import checks must scan `withStrings`, because a module specifier IS a
 * string. That makes any file which legitimately QUOTES an import statement
 * look like it contains one: scripts/verify/guard-failure-drills.mjs carries
 * "import { globSync } from 'node:fs'" as drill payload, and the first version
 * of this guard duly failed the build over it. A guard that cries wolf gets
 * switched off, and a switched-off guard is worse than none.
 *
 * `stripComments` and `stripNonCode` both preserve byte offsets, so the two
 * views can be compared position by position. Every regex here starts on
 * `import`, `from`, `require` or `{`, never on whitespace, so if the same offset
 * is blank in the strings-removed view then the match lives inside a string and
 * is prose, not code.
 */
function atRealCode(code, index) {
  return code[index] !== undefined && code[index] !== ' '
}

/** Every `node:x` builtin specifier a file imports, with its offset. */
function builtinImports(withStrings, code) {
  const found = []
  const re = /(?:from\s*|require\(\s*)['"]node:([a-z/]+)['"]/g
  let m
  while ((m = re.exec(withStrings)) !== null) {
    if (!atRealCode(code, m.index)) continue
    found.push({ module: m[1], index: m.index })
  }
  return found
}

for (const file of FILES) {
  // `withStrings` keeps module specifiers, which ARE strings, so the import
  // checks can see them. `code` blanks strings too, so the identifier checks
  // cannot match their own denylist. Comments are blanked in both, so a script
  // that merely NAMES an API in its documentation, as this one does, is safe.
  const { withStrings, code } = readSource(join(ROOT, file))

  // -------------------------------------------------------------------------
  // CHECK 1: every built-in module a script imports must exist in Node 20.
  // -------------------------------------------------------------------------
  for (const { module, index } of builtinImports(withStrings, code)) {
    if (MODULES.has(module)) continue
    failures.push(
      `${file}:${lineAt(withStrings, index)} imports 'node:${module}', which does not exist\n` +
        `          in Node ${CONTRACT_MAJOR}. .nvmrc pins Node ${CONTRACT_MAJOR} and CI installs it.`,
    )
  }

  // -------------------------------------------------------------------------
  // CHECK 2: every NAMED import from a built-in must be a real export of it in
  // Node 20. This is the import-time SyntaxError class: the 2026-08-05 defect.
  // -------------------------------------------------------------------------
  const namedFromBuiltin = [
    /import\s*\{([^}]*)\}\s*from\s*['"]node:([a-z/]+)['"]/g,
    /\{([^}]*)\}\s*=\s*require\(\s*['"]node:([a-z/]+)['"]\s*\)/g,
  ]
  for (const re of namedFromBuiltin) {
    re.lastIndex = 0
    let m
    while ((m = re.exec(withStrings)) !== null) {
      if (!atRealCode(code, m.index)) continue
      const exported = SURFACE.moduleExports[m[2]]
      // null means Node 20 could not enumerate that module standalone. Skipping
      // is the honest response: inventing an export list would be a guess.
      if (!exported) continue
      const known = new Set(exported)
      for (const raw of m[1].split(',')) {
        const name = raw.trim().split(/\s+as\s+|\s*:\s*/)[0].trim()
        if (!name || known.has(name)) continue
        failures.push(
          `${file}:${lineAt(withStrings, m.index)} imports { ${name} } from 'node:${m[2]}',\n` +
            `          which Node ${CONTRACT_MAJOR} does not export. .nvmrc pins Node ${CONTRACT_MAJOR}.\n` +
            `          This is a SyntaxError at IMPORT, so the script dies before its first\n` +
            `          line and no local run on a newer Node can reveal it.`,
        )
      }
    }
  }

  // -------------------------------------------------------------------------
  // CHECK 3: every static member of a well-known global must exist in Node 20.
  // The receiver is the global itself, so an absent name is a certain break.
  // -------------------------------------------------------------------------
  for (const [globalName, members] of Object.entries(SURFACE.globals)) {
    const known = new Set(members)
    // (?<![\w$.]) so `res.Error.x` and `myObject` do not masquerade as the global.
    const re = new RegExp(`(?<![\\w$.])${globalName}\\.([A-Za-z_$][\\w$]*)`, 'g')
    let m
    while ((m = re.exec(code)) !== null) {
      if (known.has(m[1])) continue
      failures.push(
        `${file}:${lineAt(code, m.index)} uses ${globalName}.${m[1]}, which Node\n` +
          `          ${CONTRACT_MAJOR} does not provide. .nvmrc pins Node ${CONTRACT_MAJOR} and CI installs it.`,
      )
    }
  }

  // -------------------------------------------------------------------------
  // CHECK 4: prototype methods added after the contract version.
  // -------------------------------------------------------------------------
  for (const { token, since, instead } of POST_CONTRACT_PROTOTYPE_METHODS) {
    if (since <= CONTRACT_MAJOR) continue
    const re = new RegExp(token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g')
    let m
    while ((m = re.exec(code)) !== null) {
      failures.push(
        `${file}:${lineAt(code, m.index)} uses ${token}, added in Node ${since}.\n` +
          `          .nvmrc pins Node ${CONTRACT_MAJOR}. Use ${instead} instead.`,
      )
    }
  }
}

// ---------------------------------------------------------------------------
// CHECK 5: no workflow may install a Node major BELOW the contract.
//
// A workflow pinned below the contract runs the platform on a runtime nothing
// else is tested on. Pinning ABOVE is allowed and deliberate: env-locks.yml runs
// on 24, and every script it runs is still held to the Node 20 floor by the
// scan above, so the higher runtime cannot hide a defect.
// ---------------------------------------------------------------------------
{
  const dir = join(ROOT, '.github', 'workflows')
  if (existsSync(dir)) {
    for (const name of readdirSync(dir).filter((f) => f.endsWith('.yml') || f.endsWith('.yaml'))) {
      const src = readFileSync(join(dir, name), 'utf8')
      const re = /node-version:\s*['"]?(\d+)/g
      let m
      while ((m = re.exec(src)) !== null) {
        const pinned = Number.parseInt(m[1], 10)
        if (pinned < CONTRACT_MAJOR) {
          failures.push(
            `.github/workflows/${name}:${lineAt(src, m.index)} pins node-version ${pinned},\n` +
              `          below the .nvmrc contract of ${CONTRACT_MAJOR}. Every script would then run\n` +
              `          on a runtime no other job tests.`,
          )
        }
      }
    }
  }
}

if (failures.length > 0) {
  console.error('\n[node-version-contract] FAILED\n')
  for (const f of failures) console.error(`  ${f}\n`)
  console.error(
    `  ${failures.length} violation(s). A script using an API newer than the .nvmrc\n` +
      `  contract passes on a modern laptop and crashes in CI. That is how three\n` +
      `  guards shipped broken on 2026-08-05.\n`,
  )
  process.exit(1)
}

console.log(
  `[node-version-contract] PASS - ${FILES.length} scripts hold to the Node ${CONTRACT_MAJOR} ` +
    `surface recorded from ${SURFACE.generatedBy}.`,
)
