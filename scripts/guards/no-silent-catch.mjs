/**
 * GUARD: no catch around I/O may swallow its error in silence.
 *
 * FOUNDER RULING, 25 August 2026:
 *
 *   "Tonight's worst finding was a bare catch {} eating a 42703 on a column that
 *   has never existed, publishing zero venue URLs while nobody noticed. Sweep
 *   every catch block in src/ and scripts/. Any that swallows an error without
 *   logging, re-throwing or recording is a defect."
 *
 * THE INCIDENT. src/app/sitemap.ts queried `venues.slug`, a column that has
 * never existed in this schema. PostgREST answered 42703. The query sat inside
 * a bare `catch {}`, so the route carried on and emitted a sitemap with a venue
 * section containing nothing. It was not a slow degradation: it published zero
 * venue URLs from the day it was written, and the only reason anybody ever found
 * out was an unrelated sweep of every URL in the sitemap.
 *
 * WHERE THE LINE IS DRAWN, AND WHY IT IS NOT DRAWN AT "EVERY CATCH".
 *
 * The sweep found 734 catch blocks in src/ and scripts/. 336 of them neither
 * log, re-throw, nor so much as name the error they caught. Failing the build on
 * all 336 would mean an exemption list of roughly two hundred entries, and an
 * exemption list that long is an inventory, not a gate: nobody reads it, and the
 * next real defect is added to it in the same commit that introduces it.
 *
 * So the gate is drawn where the defect actually lives: A CATCH AROUND
 * SOMETHING OUTSIDE THE PROCESS. A database query, a network call, a filesystem
 * read, a subprocess, a payment or mail API. When one of those fails there is an
 * incident, and a silent catch is the thing that decides nobody will hear about
 * it.
 *
 * A catch around `JSON.parse`, `new URL`, `decodeURIComponent` or `atob` is the
 * other thing entirely. The throw IS the answer to a question the code asked on
 * purpose, usually about a value a stranger typed. There is no incident, and
 * reporting one would be noise generated by user input. Those are counted and
 * printed on every run, so the class stays visible, but they do not fail.
 *
 * A catch SPEAKS if it re-throws, logs, reports through the observability seam,
 * or so much as names its binding. Naming the binding is enough because that is
 * what "recording" looks like in practice: putting the error into a returned
 * result, a failures array, a status field, a message. What it is NOT is
 * discarding it, which is precisely what `catch {}` does: there is not even a
 * name by which the error could be carried anywhere.
 *
 * WHAT THIS GUARD CANNOT SEE, said plainly rather than implied:
 *
 *  - It reads text, not types. `.from(` is how a Supabase query starts and also
 *    how `Buffer.from` starts, so the built-in forms are excluded by name. That
 *    exclusion is a list, and a list can be short by one.
 *  - It does not follow a call. A silent catch around `doTheThing()` whose body
 *    queries the database is invisible here.
 *  - It says nothing about the OTHER silent failure on this platform, which is
 *    about five times the size of this one. PostgREST does not throw; it returns
 *    `{ data, error }`, so an error can be discarded with no catch block
 *    anywhere near it. Measured over src/ on 25 August 2026: 757 destructures of
 *    an awaited .from()/.rpc(), of which 497 never name the error at all and 142
 *    collapse it to a boolean. Only 118 carry its detail anywhere. That is a
 *    separate sweep and is named with its number here so it cannot be mistaken
 *    for something this guard covers.
 */
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { catchBlocks, catchSpeaks, tryTouchesTheWorld } from '../lib/js-source.mjs'

const SEP = String.fromCharCode(92)
const ROOTS = ['src', 'scripts']
const EXT = /\.(ts|tsx|mjs|js)$/

/**
 * REVIEWED EXEMPTIONS. Printed on every run, with the reason, so this list can
 * never quietly become the place defects go. A file listed here is skipped
 * entirely; each entry has to justify why silence is the correct behaviour.
 */
const EXEMPT = [
  {
    prefix: 'src/lib/observability/',
    why: 'the reporter itself: reporting its own failure to report would recurse',
  },
  {
    prefix: 'src/instrumentation',
    why: 'runs before the reporter exists, by definition',
  },
  {
    prefix: 'scripts/verify/sentry-',
    why: 'proves the reporting path, including its failure modes, on purpose',
  },
  {
    prefix: 'scripts/guards/no-silent-catch.mjs',
    why: 'this guard: its own catches are read by itself and would be circular',
  },
]

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry === '.next' || entry === 'dist') continue
    const p = join(dir, entry)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (EXT.test(entry)) out.push(p)
  }
  return out
}

const files = []
for (const root of ROOTS) walk(root, files)

let scanned = 0
let total = 0
let speaking = 0
let quietButPure = 0
let exemptedFiles = 0
const violations = []

for (const file of files) {
  const rel = file.replaceAll(SEP, '/')
  const exemption = EXEMPT.find((e) => rel.startsWith(e.prefix))
  if (exemption) {
    exemptedFiles += 1
    continue
  }
  scanned += 1
  for (const block of catchBlocks(readFileSync(file, 'utf8'))) {
    total += 1
    if (catchSpeaks(block)) {
      speaking += 1
      continue
    }
    if (!tryTouchesTheWorld(block.tryBody)) {
      quietButPure += 1
      continue
    }
    violations.push({
      file: rel,
      line: block.line,
      body: block.body.trim().replace(/\s+/g, ' ').slice(0, 60) || '(empty)',
    })
  }
}

console.log(`no-silent-catch: ${scanned} files scanned under ${ROOTS.join(', ')}`)
console.log(`  ${total} catch blocks read`)
console.log(`  ${speaking} speak (re-throw, log, report, or name the error)`)
console.log(`  ${quietButPure} silent around a parse or a probe, which is the answer, not an incident`)
console.log(`  ${violations.length} silent around I/O`)
console.log(`  reviewed exemptions (${exemptedFiles} files):`)
for (const e of EXEMPT) console.log(`    ${e.prefix}  ${e.why}`)

if (violations.length > 0) {
  console.error(`\nFAIL: ${violations.length} catch block(s) discard an error from outside the process.`)
  for (const v of violations) console.error(`  ${v.file}:${v.line}  ${v.body}`)
  console.error('')
  console.error('Give it a voice: name the binding and do ONE of')
  console.error('  throw                                     if the caller must know')
  console.error('  captureException(error, { where })        server code')
  console.error('  reportClientError(error, { where })       client components (no Sentry in the bundle)')
  console.error('  console.warn(...)                         scripts')
  console.error('  return/record something carrying `error`  when the caller reports it')
  process.exit(1)
}

console.log('\nPASS: every catch around I/O says something.')
