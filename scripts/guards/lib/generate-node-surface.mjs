/**
 * Generate the API-surface manifest the node-version-contract guard checks against.
 *
 * WHY A MANIFEST AND NOT A DENYLIST. The first version of the contract guard
 * carried a hand-written list of "APIs newer than Node 20". A denylist only ever
 * knows what somebody remembered to add, so it would have caught `globSync`
 * (because that is the one that burned us) and sailed straight past the next
 * one. Inverting it fixes that: record what Node 20 ACTUALLY HAS, then treat
 * anything absent from that record as a violation. An API added in Node 25 that
 * nobody has heard of is caught on the day it is used, with no list to maintain.
 *
 * WHY IT IS A CHECKED-IN FILE. The manifest must be produced BY the contract
 * version, because only Node 20 can enumerate Node 20's surface. If the guard
 * enumerated at run time it would describe whatever Node the developer happens
 * to have, which is precisely the mistake that caused the 2026-08-05 failure.
 * Generating once under Node 20 and committing the result means the guard gives
 * the same verdict on Node 20, Node 24, and CI.
 *
 * REGENERATE ONLY when .nvmrc changes, and only under the new contract version:
 *
 *   npm run guards:surface
 *
 * which refuses to run on the wrong major, so the file cannot be regenerated
 * against the wrong Node by accident.
 */
import { builtinModules } from 'node:module'
import { writeFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..', '..', '..')

const contract = Number.parseInt(readFileSync(join(ROOT, '.nvmrc'), 'utf8').trim().replace(/^v/, ''), 10)
const running = Number.parseInt(process.versions.node.split('.')[0], 10)

if (running !== contract) {
  console.error(
    `\n[generate-node-surface] REFUSING TO RUN.\n\n` +
      `  .nvmrc pins Node ${contract}. This process is Node ${process.versions.node}.\n` +
      `  A manifest generated on the wrong major would describe the wrong platform and\n` +
      `  would silently bless every API the contract version does not have. That is the\n` +
      `  exact class of mistake this manifest exists to prevent.\n\n` +
      `  Run it under the contract version:  npm run guards:contract-node -- --surface\n`,
  )
  process.exit(1)
}

/**
 * Globals whose STATIC members are worth recording. A `Promise.withResolvers`
 * or `Object.groupBy` in source is unambiguous: the receiver is the global
 * itself, so an absent name is a certain break rather than a guess.
 */
const GLOBALS = [
  'Object',
  'Array',
  'Promise',
  'Map',
  'Set',
  'WeakMap',
  'WeakSet',
  'RegExp',
  'Error',
  'JSON',
  'Math',
  'Reflect',
  'String',
  'Number',
  'Symbol',
  'process',
]

const surface = {
  /** Provenance, so a stale or wrongly generated manifest is self-evident. */
  generatedBy: `node ${process.version}`,
  contractMajor: contract,
  /** Every built-in module name, without the node: prefix duplicates. */
  modules: [...new Set(builtinModules.filter((m) => !m.startsWith('_')))].sort(),
  /** Named exports of each built-in module. */
  moduleExports: {},
  /** Static members of the well-known globals. */
  globals: {},
  /** Names that exist directly on globalThis. */
  globalThis: Object.getOwnPropertyNames(globalThis).sort(),
}

for (const name of surface.modules) {
  try {
    const mod = await import(`node:${name}`)
    surface.moduleExports[name] = Object.keys(mod).sort()
  } catch {
    // Some builtins refuse to load standalone (node:test without a runner, the
    // flagged ones). Recording them as unknown is honest: the guard skips a
    // module it has no export list for rather than inventing one.
    surface.moduleExports[name] = null
  }
}

for (const name of GLOBALS) {
  const value = globalThis[name]
  if (value === undefined || value === null) continue
  surface.globals[name] = Object.getOwnPropertyNames(value).sort()
}

const out = join(HERE, 'node-surface.json')
writeFileSync(out, `${JSON.stringify(surface, null, 2)}\n`, 'utf8')

console.log(
  `[generate-node-surface] wrote ${out.replace(/\\/g, '/')}\n` +
    `  generated by ${surface.generatedBy} for the Node ${contract} contract\n` +
    `  ${surface.modules.length} builtin modules, ${Object.keys(surface.globals).length} globals recorded`,
)
